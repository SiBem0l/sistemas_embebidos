/* USER CODE BEGIN 4 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
	if(GPIO_Pin == count.input_pin.pin)
	{
		osSemaphoreRelease(countPressedSemaphore);
	}
	else if(GPIO_Pin == reset.input_pin.pin)
	{
		osSemaphoreRelease(resetPressedSemaphore);
	}
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == UART4)
    {
        BaseType_t xHigherPriorityTaskWoken = pdFALSE;

        // 1. Guardar el byte (pasamos el puntero de xHigherPriorityTaskWoken)
        comunication_store_byte_isr(&comunication, &xHigherPriorityTaskWoken);

        // 2. Preparar el periférico para recibir el siguiente byte
        comunication_ready(&comunication);

        // 3. Evaluar si es necesario cambiar de contexto al salir
        portYIELD_FROM_ISR(xHigherPriorityTaskWoken);
    }
}

