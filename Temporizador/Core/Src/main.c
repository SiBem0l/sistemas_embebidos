	MX_UART4_Init();
	MX_TIM2_Init();
	/* USER CODE BEGIN 2 */

	// Now it is safe for the timer to fire, because everything it needs is ready.
	timer_ready(&timer);

	comunication_ready(&comunication);
	comunication_send(&comunication, "CONNECTED\n");

	/* USER CODE END 2 */

	/* Infinite loop */
	/* USER CODE BEGIN WHILE */
	while (1)
	{
		/* USER CODE END WHILE */

		/* USER CODE BEGIN 3 */
		char data [BUFFER_SIZE];
		strcpy(data, comunication_get_data(&comunication));
		char last_byte = comunication.recived_byte;

		if (last_byte == '\0' && strlen(data) > 0)
		{
			// Limpiar el buffer para recibir el próximo mensaje desde cero
			comunication_clear_buffer(&comunication);

			// Traducir el string al comando correspondiente (Enum Instruction)
			Instruction cmd = instruction_read(data);

			// Ejecutar la acción sobre el temporizador y la UART
			if(cmd == INVALID)
			{
				comunication_send(&comunication, "INVALID INSTRUCTION\n");
			}
			else
			{
				instruction_execute(cmd, data, &timer, &comunication);
				if(cmd == RESET_TIMER)
				{
					buzzer_off(&buzzer);
				}
				comunication_send(&comunication, "OK\n");
			}
		}

	}
	/* USER CODE END 3 */
