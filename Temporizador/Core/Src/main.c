	timer = timer_new(&htim1, 0);
	display = display_new();
	count = button_new(button_count_GPIO_Port, button_count_Pin);
	reset = button_new(button_reset_GPIO_Port, button_reset_Pin);
	comunication = comunication_new(&huart4);
	buzzer = buzzer_new(&htim2, TIM_CHANNEL_4);

	/* USER CODE END SysInit */

